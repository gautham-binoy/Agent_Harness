def generate_tasks():
    base_dir = Path("benchmark/tasks")
    difficulty_counts = {"easy": 0, "medium": 0, "hard": 0}
    category_counts = {}

    for t in TASKS:
        cat_dir = base_dir / t["category"]
        cat_dir.mkdir(parents=True, exist_ok=True)
        task_file = cat_dir / f"{t['id']}.yaml"
        with open(task_file, "w", encoding="utf-8") as f:
            yaml.safe_dump(t, f, default_flow_style=False)

        difficulty_counts[t["difficulty"]] = difficulty_counts.get(t["difficulty"], 0) + 1
        category_counts[t["category"]] = category_counts.get(t["category"], 0) + 1

    print(f"Generated {len(TASKS)} benchmark tasks.")
    print(f"Categories: {category_counts}")
    print(f"Difficulties: {difficulty_counts}")


if __name__ == "__main__":
    generate_tasks()
